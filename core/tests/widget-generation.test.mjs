import assert from 'node:assert/strict';
import { test } from 'node:test';
import { BACKGROUND_CONTEXT } from '@earendil-works/chord/context';
import { validateToolArguments } from '@earendil-works/pi-ai/utils/validation';
import { createRegistry, createSession, MemoryStorage } from '@earendil-works/pi-durable';
import { Type } from 'typebox';
import { installHarness } from '../dist/agent/catalog.js';
import { checkItem, createPanelTool, keepWidget, PanelDoc } from '../dist/panel.js';
import { SendInput } from '../dist/protocol/send.js';
import { deliveredSentIn } from '../dist/conversation/transcript.js';
import { createSendTool, defineSendCard } from '../dist/send/tool.js';

const ctx = BACKGROUND_CONTEXT;
const send = body => ({
  type: 'widget',
  widget: { kind: 'panel', panel: { id: body.kind, size: 'm', title: body.kind, body } },
});
const ordinaryBodies = [
  { kind: 'stat', value: 'Countdown', at: 1900000000000 },
  { kind: 'gauge', items: [{ label: 'Quota', value: 1, max: 2 }] },
  { kind: 'chart', mark: 'line', x: ['Mon'], series: [{ name: 'Steps', values: [5] }] },
  { kind: 'list', items: [{ title: 'Plain row' }, { title: 'Task', done: false }] },
  { kind: 'timeline', events: [{ at: 1900000000000, title: 'Flight' }] },
  { kind: 'note', markdown: 'Hello' },
  { kind: 'media', src: 'https://example.com/photo.png' },
  { kind: 'weather', city: 'Singapore' },
  { kind: 'actions', buttons: [{ label: 'Summarize', prompt: 'Summarize this' }] },
];
const checklist = send({ kind: 'list', items: [{ title: 'Pack', done: false }] });
const space = send({ kind: 'space', src: 'artifact://spaces/space/index.html@1', preview: 'artifact://spaces/space/cover.html@1' });
const registry = createRegistry();
installHarness(registry, ['send'], { host: { env: {} } });
const [{ tool: sendTool }] = registry.snapshot().tools();
const panelTool = createPanelTool();
const validate = (tool, args) => validateToolArguments(tool, { name: tool.name, arguments: args });

test('only Checklists can be generated by the model, with a separate Schedule Overview request', () => {
  for (const body of ordinaryBodies) {
    const input = send(body);
    assert.deepEqual(validate({ name: 'stored send', parameters: SendInput }, input), input);
    assert.throws(() => validate(sendTool, input), /Validation failed/);
    assert.throws(() => validate(panelTool, { action: 'update', widget: input.widget.panel }), /Validation failed/);
  }
  assert.deepEqual(validate(sendTool, checklist), checklist);
  assert.throws(() => validate(sendTool, send({ kind: 'list', items: [] })), /Validation failed/);
  assert.throws(() => validate(sendTool, send({ kind: 'list', items: Array(9).fill({ title: 'Task', done: false }) })), /Validation failed/);
  assert.deepEqual(validate({ name: 'stored send', parameters: SendInput }, space), space);
  assert.throws(() => validate(sendTool, space), /Validation failed/);
  assert.throws(() => validate(panelTool, { action: 'update', widget: space.widget.panel }), /Validation failed/);
  assert.doesNotThrow(() => validate(panelTool, { action: 'update', widget: checklist.widget.panel }));
  assert.doesNotThrow(() => validate(sendTool, { type: 'widget', widget: { kind: 'asset', title: 'File', ref: 'artifact://file.html@1' } }));
  assert.doesNotThrow(() => validate(sendTool, { type: 'widget', widget: { kind: 'panel', panel: { body: { kind: 'schedules' } } } }));
  assert.throws(() => validate(sendTool, send({ kind: 'schedules', revision: 1, rows: [] })), /Validation failed/);
});

test('historical sends still load, keep and list all their original widget bodies', async t => {
  const session = createSession(new MemoryStorage());
  t.after(() => session.close(ctx));
  const entries = ordinaryBodies.flatMap((body, index) => [
    { id: index * 2 + 1, kind: 'pi.assistant', model: [{
      content: [{ type: 'toolCall', name: sendTool.name, id: body.kind, arguments: send(body) }],
    }] },
    { id: index * 2 + 2, kind: 'pi.tool-result', model: [{ role: 'toolResult', toolName: sendTool.name, toolCallId: body.kind }] },
  ]);
  const sent = deliveredSentIn(entries);
  assert.deepEqual(sent.map(offer => offer.input.widget.panel.body), ordinaryBodies);
  for (const offer of sent) await keepWidget(session, entries, offer.id, true);
  await checkItem(session, 'list', 1, true);
  await assert.rejects(checkItem(session, 'list', 0, true), /不能勾选/);
  const kept = await session.snapshot(PanelDoc, ctx);
  const api = { snapshot: session.snapshot.bind(session), commit: session.commit.bind(session) };
  const listed = await panelTool.execute({ action: 'list' }, api, ctx);
  assert.deepEqual(JSON.parse(listed.output[0].text), kept.order.map(id => kept.widgets[id]));
  assert.deepEqual(kept.widgets.list.body.items, [{ title: 'Plain row' }, { title: 'Task', done: true }]);
  const incompatibleUpdate = await panelTool.execute({ action: 'update', widget: checklist.widget.panel }, api, ctx);
  assert.equal(incompatibleUpdate.isError, true);
  assert.deepEqual(await session.snapshot(PanelDoc, ctx), kept);
});

test('completed checklists stay saved without using a visible Panel slot', async t => {
  const session = createSession(new MemoryStorage());
  t.after(() => session.close(ctx));
  const completed = checklist.widget.panel;
  await session.commit(async tx => {
    const panel = await tx.doc(PanelDoc);
    panel.order = [...Array.from({ length: 23 }, (_, index) => 'existing-' + index), completed.id];
    panel.widgets[completed.id] = { ...completed, updatedAt: 1 };
  }, ctx);

  const offer = send({ kind: 'list', items: [{ title: 'New item', done: false }] });
  offer.widget.panel.id = 'new-checklist';
  const entries = [
    { id: 1, kind: 'pi.assistant', model: [{ content: [{ type: 'toolCall', name: sendTool.name, id: 'new', arguments: offer }] }] },
    { id: 2, kind: 'pi.tool-result', model: [{ role: 'toolResult', toolName: sendTool.name, toolCallId: 'new' }] },
  ];

  await assert.rejects(keepWidget(session, entries, 'new', true), /视图已满/);
  await checkItem(session, completed.id, 0, true);
  await keepWidget(session, entries, 'new', true);
  const panel = await session.snapshot(PanelDoc, ctx);
  assert.ok(panel.widgets['new-checklist']);
  assert.equal(panel.widgets[completed.id].body.items[0].done, true);
});

test('a contribution supplies a model schema, guidance, and the card that Chat keeps', async () => {
  const card = { kind: 'asset', ref: 'artifact://report.md@2', title: 'Report' };
  const extension = defineSendCard({
    schema: Type.Object({ kind: Type.Literal('saved-report'), report: Type.String() }),
    instructions: ['Use saved-report to deliver a previous report.'],
    prepare(input) {
      if (input.report !== 'known') return { error: 'Unknown report' };
      return { card };
    },
  });
  const tool = createSendTool([extension, { instructions: ['Include a message after background work.'] }]);
  const input = { type: 'widget', widget: { kind: 'saved-report', report: 'known' }, end_turn: true };
  const api = { conversationId: 'root', snapshot: async () => undefined };
  assert.match(tool.description, /Use saved-report/);
  assert.match(tool.description, /after background work/);
  assert.deepEqual(validate(tool, input), input);
  assert.throws(() => validate(createSendTool([]), input), /Validation failed/);
  const rejected = await tool.execute({ ...input, widget: { ...input.widget, report: 'missing' } }, api, ctx);
  assert.equal(rejected.isError, true);
  const result = await tool.execute(input, api, ctx);
  assert.deepEqual(result.details.widget, card);
  assert.deepEqual(result.control, { terminate: true });
  const entries = [
    { id: 1, kind: 'pi.assistant', model: [{ content: [{ type: 'toolCall', name: tool.name, id: 'report', arguments: input }] }] },
    { id: 2, kind: 'pi.tool-result', model: [{ role: 'toolResult', toolName: tool.name, toolCallId: 'report', details: result.details }] },
  ];
  assert.deepEqual(deliveredSentIn(entries).map(offer => offer.input.widget), [card]);
});

test('the registered Artifact and Space contributions validate their own offers', async () => {
  const registry = createRegistry();
  const checked = [];
  installHarness(registry, ['send'], {
    host: {
      name: 'test',
      env: {
        S3_ENDPOINT: 'https://s3.example.test', S3_BUCKET: 'test',
        S3_ACCESS_KEY_ID: 'test', S3_SECRET_ACCESS_KEY: 'test',
        CONTEXT_DEV_API_KEY: 'test', LULU_SPACE_WEBHOOK_SECRET: 'test'.repeat(8),
        LULU_SPACE_WEBHOOK_ORIGIN: 'https://hooks.example.test',
        LULU_SPACE_PRIVATE_ORIGIN: 'https://private.example.test',
      },
      objects: { ARTIFACTS: { getByName: () => ({ fetch: async url => {
        const { pathname, searchParams } = new URL(url);
        assert.equal(pathname, '/stat');
        const name = searchParams.get('name');
        checked.push([name, searchParams.get('version')]);
        return new Response(null, { status: name === 'missing.html' ? 404 : 204 });
      } }) } },
    },
  });
  const [{ tool }] = registry.snapshot().tools();
  const api = { conversationId: 'root', snapshot: async () => undefined };
  const asset = { type: 'widget', widget: { kind: 'asset', title: 'File', ref: 'artifact://missing.html@3' } };
  const missing = await tool.execute(validate(tool, asset), api, ctx);
  assert.equal(missing.isError, true);
  assert.match(missing.output[0].text, /does not exist/);

  const offer = send({
    ...space.widget.panel.body,
    monitor: { url: 'https://example.test/data', goal: 'Find changes', schema: { type: 'object', properties: {} } },
  });
  const accepted = await tool.execute(validate(tool, offer), api, ctx);
  assert.deepEqual(accepted.details.widget, offer.widget);
  assert.deepEqual(checked, [['missing.html', '3'], ['spaces/space/index.html', '1'], ['spaces/space/cover.html', '1']]);
  const unconfigured = await sendTool.execute(validate(sendTool, offer), api, ctx);
  assert.match(unconfigured.output[0].text, /monitoring is unavailable/);
});
